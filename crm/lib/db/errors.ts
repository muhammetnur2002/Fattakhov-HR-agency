/**
 * Нарушение уникального индекса.
 *
 * Проверки «такой уже есть» сервисы делают отдельным запросом перед
 * записью — чтобы человек получил понятное сообщение и ссылку на
 * существующую карточку, а не текст про constraint. Но между проверкой
 * и записью помещается второй такой же вызов: два клика по одной
 * кнопке, две открытые вкладки, повтор запроса после таймаута. Тогда
 * последнее слово остаётся за базой, и её отказ нужно превратить
 * в то же самое понятное сообщение, а не показывать как сбой.
 *
 * Опознаём по коду Prisma, а не по тексту сообщения: текст меняется
 * от версии к версии, код — часть публичного контракта.
 */
export function isUniqueViolation(error: unknown): boolean {
  return (
    typeof error === "object" &&
    error !== null &&
    (error as { code?: string }).code === "P2002"
  );
}
