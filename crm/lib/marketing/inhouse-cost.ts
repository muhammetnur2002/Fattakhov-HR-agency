/**
 * Общий тариф страховых взносов работодателя.
 *
 * Это значение по умолчанию в поле калькулятора, а не заявление о рынке:
 * у части компаний, например у малого и среднего бизнеса, ставка ниже,
 * и зависит она ещё от предельной базы. Поэтому поле правится, а под ним
 * стоит пояснение.
 *
 * НДФЛ сюда не входит намеренно: он удерживается из оклада, а не
 * добавляется к нему, и прибавлять его к расходам работодателя - типичная
 * ошибка, на которой такие расчёты и ловят.
 */
export const GENERAL_CONTRIBUTIONS_RATE = 0.3;

export type CostBreakdown = {
  salaries: number;
  contributions: number;
  tools: number;
  total: number;
};

/**
 * Стоимость своей команды в месяц по цифрам, которые ввёл посетитель.
 *
 * Оклады, ставка и инструменты приходят снаружи: у функции нет своих
 * чисел, а значит, нечего защищать перед финансовым директором. Пустой
 * список окладов даёт ноль, а не «типичную» сумму.
 */
export function inhouseMonthlyCost(
  salaries: number[],
  rate: number = GENERAL_CONTRIBUTIONS_RATE,
  tools = 0,
): CostBreakdown {
  const total = salaries.reduce((sum, s) => sum + s, 0);
  const contributions = Math.round(total * rate);

  return {
    salaries: total,
    contributions,
    tools,
    total: total + contributions + tools,
  };
}

/**
 * Насколько подписка дешевле, в процентах.
 *
 * Округляем вниз: заявлять «экономия 83%» при 83.4 честнее, чем
 * округлять вверх до 84.
 */
export function savingsPercent(inhouse: number, subscription: number): number {
  if (inhouse <= 0) return 0;
  return Math.floor(((inhouse - subscription) / inhouse) * 100);
}

