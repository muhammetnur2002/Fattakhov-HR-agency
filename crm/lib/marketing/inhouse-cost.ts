/**
 * Тарифы агентства и расчёт «во что обходится своя команда найма».
 *
 * Правило публичных страниц: на них нет ни одного числа, которое держится
 * на допущении, а не на подтверждённых данных. Тарифы подтверждены, цена
 * вакансии из них считается арифметикой, а стоимость своего отдела считает
 * калькулятор по цифрам самого посетителя: оклады и расходы на инструменты
 * вводит он, ставку взносов он видит и правит.
 *
 * Раньше здесь лежали готовые оклады, ставка взносов и стоимость
 * инструментов, и из них на первом экране, в описаниях для поисковиков
 * и в разметке FAQ получались «во сколько обходится отдел» и «сколько
 * остаётся за год». Подтверждены они не были, а это реклама со сравнением,
 * и первым такой расчёт разбирает финансовый директор клиента. Вернуть
 * готовые цифры можно только вместе с подтверждением бухгалтера и указанием,
 * откуда они. Тест tests/inhouse-cost.test.ts следит, чтобы старые итоги
 * не вернулись на страницы молча.
 *
 * Имя файла осталось от прежнего содержимого; тарифная лестница живёт здесь же.
 */

