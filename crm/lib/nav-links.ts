export const AGENCY_HOME = "/a";
export const CLIENT_HOME = "/dashboard";

/**
 * Имя ссылки на раздел для читалок экрана.
 *
 * Счётчик лежит внутри ссылки, и без отдельной подсказки читалка склеивала
 * его с названием: «Сообщения3», «3Сообщения». С подсказкой — «Сообщения,
 * непрочитанных: 3». Нет счётчика — undefined: имя берётся из текста ссылки,
 * как раньше. Сам кружок на таких ссылках скрыт от читалки (aria-hidden),
 * иначе число прозвучало бы дважды.
 */
export function navLinkLabel(item: { label: string; badge?: number }): string | undefined {
  return item.badge ? `${item.label}, непрочитанных: ${item.badge}` : undefined;
}
