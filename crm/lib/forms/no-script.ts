/**
 * Безопасная отправка формы, которая работает только через клиентский код.
 *
 * Зачем. Форма с `onSubmit` и `preventDefault`, у которой нет `action` и `method`, в разметке сервера —
 * обычная HTML-форма, а обычная форма отправляется методом GET. Пока скрипты не загрузились (медленный
 * телефон, блокировщик, не пришёл чанк), нажатие кнопки или Enter уносит поля в адресную строку, историю
 * браузера и журналы Caddy: пароль для включения 2FA, ответы анкеты (`?company=…`), данные кандидата.
 * Проверено в браузере с неподгруженными скриптами (12.10.2026): `/settings?proof=<пароль>`,
 * `/onboarding?company=<название>`.
 *
 * Что здесь. `method="post"` и адрес обработчика, который тело не читает и ничего не отражает в адресе:
 * он отправляет человека назад на ту же страницу (`app/api/no-script-form/route.ts`). После загрузки
 * скриптов `onSubmit` гасит стандартную отправку, и эти атрибуты не используются.
 *
 * Когда брать. Форма уходит через `onSubmit` в клиентский код, а сервер ждёт не `FormData`
 * (`updateCandidateProfileAction(id, values)`, `phoneSignInAction({ … })`) — серверным действием через
 * `action` её не отправить:
 *
 * ```tsx
 * <form {...noScriptForm} onSubmit={(e) => { e.preventDefault(); save(); }}>
 * ```
 *
 * Не брать, когда есть серверное действие над `FormData` — тогда `action={действие}` (форма работает и без
 * скриптов, прогрессивное улучшение), и когда форма на `useFormAction` — там `{...formProps}`. Нужен ли
 * `noScriptForm` форме, проверяет `tests/form-submit-guard.test.ts`: любая `<form>` без `action` и
 * `method` — красный тест.
 *
 * Модуль без импортов: его берут клиентские компоненты.
 */
export const NO_SCRIPT_FORM_PATH = "/api/no-script-form";

export const noScriptForm = { method: "post", action: NO_SCRIPT_FORM_PATH } as const;
