/**
 * Единственное место, где обычная календарная дата превращается в текст
 * для человека.
 *
 * До этого модуля одна и та же по смыслу дата форматировалась по-разному
 * в разных углах кабинета клиента: «06.08.2026» на странице вакансии
 * и «22 июня 2026 г.» в «Документах» — на одном экране, в соседних
 * карточках. Длинный месяц выбран каноническим: для договора и счёта
 * это единственно уместный вид, а для остальных мест разница просто
 * не критична.
 */
export function formatDate(date: Date | string): string {
  return new Intl.DateTimeFormat("ru-RU", {
    day: "2-digit",
    month: "long",
    year: "numeric",
  }).format(new Date(date));
}
