/**
 * Можно ли слать письмо на этот адрес.
 *
 * Заглушки быстрой регистрации (…@users.invalid, см.
 * lib/services/quick-registration.ts) — нет: домен .invalid
 * зарезервирован стандартом (RFC 2606) и не доставляется никуда,
 * а попытка — это отказ почтового сервера в журнале и «отправлено»
 * в отметках уведомления.
 *
 * Отдельный файл без зависимостей: его читают и рассылка уведомлений,
 * и почтовый транспорт, а сервис регистрации сам зависит от рассылки —
 * положи функцию туда, и импорты замкнулись бы в круг.
 */
export function isDeliverableEmail(email: string): boolean {
  return !/\.invalid$/i.test(email.trim());
}
