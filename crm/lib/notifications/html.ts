/**
 * Экранирование для писем в HTML.
 *
 * Экранировать обязательно: имена, названия компаний и вакансий, тексты
 * уведомлений приходят из форм без всякой цензуры символов. Без этого
 * компания с именем `<b>` или `"` сломала бы вёрстку письма, а с именем
 * вида `<img src=x onerror=...>` — исполнила бы код в почтовом клиенте
 * получателя: письма рендерятся как настоящий HTML.
 */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
