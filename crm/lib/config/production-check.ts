import {
  CANDIDATE_CONSENT_VERSION,
  DRAFT_CANDIDATE_CONSENT_VERSION,
} from "@/lib/legal/candidate-consent";

/**
 * Проверка настроек на запуске.
 *
 * Отдельные модули уже умеют отказываться работать без своих настроек —
 * хранилище файлов без S3, почта без SMTP. Но оба отказа ленивые: они
 * случаются на первом обращении, то есть когда рекрутёр открыл резюме
 * или платформа собралась отправить приглашение. К этому моменту
 * выкатка давно объявлена успешной, а разбираться приходится по жалобе
 * живого человека.
 *
 * Здесь те же требования собраны в одно место и проверяются один раз,
 * до первого запроса (см. instrumentation.ts). Плохая настройка должна
 * ронять выкатку, а не первого пользователя.
 *
 * Проверяется только то, без чего платформа именно что неисправна.
 * Telegram сюда не входит: это канал по желанию, и его отсутствие
 * означает «такой возможности нет», а не потерянное письмо.
 */

type Requirement = {
  /** Что перестанет работать. Человеческим языком: это читают в логе выкатки. */
  breaks: string;
  /**
   * Переменные, нужные все сразу. Через `|` — «любая из»,
   * для взаимозаменяемых.
   */
  vars: string[];
};

const REQUIREMENTS: Requirement[] = [
  {
    breaks:
      "Файлы кандидатов (резюме) обязаны лежать в российском S3 (BR-32). " +
      "Без этого они попадут на диск сервера и пропадут при перезапуске",
    vars: [
      "S3_ENDPOINT",
      "S3_BUCKET",
      "S3_ACCESS_KEY_ID",
      "S3_SECRET_ACCESS_KEY",
    ],
  },
  {
    breaks:
      "Почта: ею уходят приглашения и ссылки сброса пароля. Без SMTP они " +
      "лягут в лог контейнера — то есть перестанут работать и окажутся " +
      "не там, где персональным данным место",
    vars: ["SMTP_URL", "SMTP_FROM"],
  },
  {
    breaks:
      "AUTH_SECRET подписывает сессии, ссылки на файлы и календарные ленты. " +
      "Без него их нечем ни выдать, ни проверить",
    vars: ["AUTH_SECRET"],
  },
  {
    breaks:
      "APP_URL (или AUTH_URL) — адрес, который платформа ставит в ссылки для " +
      "людей: приглашение, согласие на ПДн, выбор времени интервью. Без него " +
      "в письме окажется localhost",
    vars: ["APP_URL|AUTH_URL"],
  },
];

/**
 * Отдельно от переменных окружения: это не настройка, а незакрытая
 * работа. Текст согласия кандидата в репозитории — заглушка с пометкой
 * «не юридический документ» (открытый вопрос раздела 19 ТЗ), и пока
 * он не заменён, собирать по нему согласия реальных людей нельзя.
 *
 * Проверка здесь потому, что заглушка не выглядит поломкой: форма
 * открывается, галочка ставится, запись в базе появляется. Отличить
 * такое согласие от настоящего можно будет только по версии внутри —
 * то есть уже постфактум, при разборе обращения.
 */
function draftConsentProblem(): string | null {
  if (CANDIDATE_CONSENT_VERSION !== DRAFT_CANDIDATE_CONSENT_VERSION) {
    return null;
  }
  return (
    "Текст согласия на обработку персональных данных — заглушка " +
    "(версия = «" +
    DRAFT_CANDIDATE_CONSENT_VERSION +
    "»), а не выверенный юристом документ. Собирать по нему согласия " +
    "кандидатов нельзя.\n  Замените текст и версию в lib/legal/candidate-consent.ts"
  );
}

function isSet(name: string): boolean {
  return name.split("|").some((key) => Boolean(process.env[key]?.trim()));
}

/**
 * Список проблем. Пустой — настройки в порядке.
 *
 * Отдельно от того, кто на них ругается: так проверку можно прогнать
 * тестом, не поднимая сервер и не подделывая NODE_ENV глобально.
 */
export function productionConfigProblems(): string[] {
  const missingVars = REQUIREMENTS.filter((req) =>
    req.vars.some((v) => !isSet(v)),
  ).map((req) => {
    const missing = req.vars.filter((v) => !isSet(v));
    return `${req.breaks}.\n  Не заданы: ${missing.join(", ")}`;
  });

  const draft = draftConsentProblem();
  return draft ? [...missingVars, draft] : missingVars;
}

/**
 * Черновик согласия — единственная проверка, которую можно осознанно
 * отключить: тем же приёмом, что WIPE_DEV_DB=yes у setup-real.ts. Только
 * для временной проверки самого деплоя (например, первый запуск на
 * Vercel), пока текст ещё не заменён юристом. S3, SMTP и AUTH_SECRET
 * этот флаг не трогает — они обязательны всегда.
 *
 * Молчать про снятую проверку нельзя: предупреждение остаётся в логе,
 * чтобы включённый на «на попробовать» флаг не забыли снять перед тем,
 * как звать настоящих кандидатов.
 */
function allowDraftConsent(): boolean {
  return process.env.ALLOW_DRAFT_CONSENT === "yes";
}

/**
 * Проверка при старте. В проде бросает, в разработке молчит.
 *
 * Разработка живёт без S3 и SMTP намеренно: файлы на диске, письма
 * в консоли — так весь движок событий проверяется, ничего не отправив
 * живым людям на тестовых данных.
 */
export function assertProductionConfig(): void {
  if (process.env.NODE_ENV !== "production") return;

  let problems = productionConfigProblems();
  if (allowDraftConsent()) {
    const draft = draftConsentProblem();
    if (draft) {
      console.warn(
        "[production-check] ALLOW_DRAFT_CONSENT=yes — платформа запущена с " +
          "черновиком согласия кандидатов. Уберите флаг, как только текст " +
          "заменит юрист.",
      );
    }
    problems = problems.filter((p) => p !== draft);
  }
  if (problems.length === 0) return;

  /*
    Замечания бывают двух родов — незаданная переменная и незакрытая
    работа, — и звать их обоих «настройками» неправильно: человек
    пойдёт искать в .env то, чего там нет и быть не может.
  */
  const aboutEnv = problems.some((p) => p.includes("Не заданы:"));

  throw new Error(
    "Платформа не запущена: она не готова к работе с боевыми данными.\n\n" +
      problems.map((p) => `• ${p}`).join("\n\n") +
      (aboutEnv
        ? "\n\nПеременные с пояснениями — в .env.example."
        : ""),
  );
}
