/**
 * Что серверное действие формы отвечает странице.
 *
 * Тип без зависимостей: его импортируют клиентские компоненты, а они не должны тянуть в браузер
 * zod (вместе с ним уходит 67 КБ). Разбор схемы в этот ответ — `lib/validation/form-errors.ts`,
 * только для сервера.
 *
 * - `fields` — ошибка у конкретного поля: ключ — имя поля формы (`name`), значение — текст для
 *   человека. Страница рисует его под полем, ставит полю `aria-invalid` и уводит фокус на первое;
 * - `error` — общая беда формы («Недостаточно прав», «Адрес уже занят») либо краткая сводка над
 *   полями, если ошибок у полей несколько;
 * - `ok` — форма сработала; сообщение читалкой объявляется вежливо (role="status").
 *
 * Пароли и коды в ответ не кладутся никогда: ни ошибкой, ни «значением поля».
 */
export type FieldErrors = Record<string, string>;

export type FormState = {
  error?: string;
  ok?: string;
  fields?: FieldErrors;
};

/** Сводка над ошибками полей: что именно не так, сказано у каждого поля. */
export const CHECK_FIELDS_MESSAGE = "Проверьте заполнение полей";
