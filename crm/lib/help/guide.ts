function isAgencyRole(role: UserRole): boolean {
  return (AGENCY_ROLES as readonly UserRole[]).includes(role);
}

/** Помощь для конкретной роли: её раздел плюс общая часть стороны. */
export function guideFor(role: UserRole): Guide {
  const agency = isAgencyRole(role);

  return {
    intro: agency
      ? "Порядок работы и правила, в которые чаще всего упираются: с чего начать, почему кандидат не представляется, что видит клиент и где деньги."
      : "Как устроена работа с агентством: с чего начать, когда появляются кандидаты, что требуется от вас и кто что видит.",
    sections: [
      { title: "Ваша роль", items: [ROLE_SECTION[role]] },
      ...(agency ? AGENCY_SECTIONS : CLIENT_SECTIONS),
    ],
  };
}
