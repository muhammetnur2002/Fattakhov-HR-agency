import { z } from "zod";

import { VACANCY_COUNT_OPTIONS } from "./lead-options";

/**
 * Варианты из формы. Свободный ввод здесь не нужен и только мешает разбору.
 * Сам список лежит в lead-options.ts — без zod, чтобы клиентская форма его не тянула.
 */
export { VACANCY_COUNT_OPTIONS };

const optional = (max: number) =>
  z
    .string()
    .trim()
    .max(max, `Слишком длинно, максимум ${max} символов`)
    .optional()
    .transform((v) => (v ? v : null));

/**
 * Заявка с лендинга.
 *
 * Обязательны только имя и способ связи. Каждое лишнее обязательное поле
 * на первом касании стоит заявок, а сайт, компанию и подробности всё
 * равно спросят на диагностике.
 */
export const leadSchema = z.object({
  name: z
    .string()
    .trim()
    .min(2, "Напишите, как к вам обращаться")
    .max(120, "Слишком длинное имя"),

  // Телефон, Telegram или почта - что удобнее человеку. Проверяем только
  // что это похоже на контакт, а не угадываем формат: строгая маска
  // отсекает и +7 (937) 571-18-77, и @goalkeeperka, и живые адреса.
  contact: z
    .string()
    .trim()
    .min(5, "Оставьте телефон, Telegram или почту")
    .max(160, "Слишком длинный контакт")
    .refine((v) => /[\d@]/.test(v), {
      message: "Похоже, это не телефон, не Telegram и не почта",
    }),

  company: optional(160),
  website: optional(200),
  note: optional(2000),

  /*
    Поле необязательное, и «не выбрано» приходит пустой строкой, а не
    отсутствующим полем: и обычный <select>, и наш компонент шлют "".
    Одного .optional() тут мало — он пропускает undefined, но не "",
    и заявка не отправлялась вовсе, пока человек не трогал этот список.
    Ошибка при этом показывалась зодовская, по-английски.
  */
  vacancies: z
    .preprocess(
      (v) => (v === "" ? undefined : v),
      z
        .enum(VACANCY_COUNT_OPTIONS, {
          message: "Выберите вариант из списка",
        })
        .optional(),
    )
    .transform((v) => v ?? null),

  /**
   * Согласие на обработку. Без него заявку принимать нельзя
   * (юридический пакет, раздел 10; ст. 9 закона в редакции
   * с 01.09.2025).
   *
   * Браузер шлёт непроставленную галочку как отсутствующее поле,
   * а проставленную как "on". Поэтому проверяется именно "on":
   * любое другое значение означает, что галочку обошли.
   */
  consent: z.literal("on", {
    message: "Без согласия на обработку данных заявку принять нельзя",
  }),

  /** Реклама - отдельно и добровольно. Обязательной быть не может. */
  marketingConsent: z
    .literal("on")
    .optional()
    .transform((v) => v === "on"),
});

export type LeadInput = z.infer<typeof leadSchema>;
