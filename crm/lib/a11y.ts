/**
 * Якорь основного содержимого страницы.
 *
 * Ссылка «Перейти к содержимому» (components/shell/skip-link.tsx) ведёт на
 * элемент <main> с этим id, а сам <main> принимает фокус программно
 * (tabIndex=-1): без этого после Enter на ссылке прокрутка уходит вниз,
 * а следующий Tab снова начинает с шапки. Константа вынесена в отдельный
 * файл без "use client": из клиентского модуля серверный компонент получил
 * бы не строку, а ссылку на модуль.
 */
export const MAIN_CONTENT_ID = "main-content";

/** Свойства для <main> каждой оболочки: якорь для ссылки «К содержимому». */
export const MAIN_LANDMARK_PROPS = {
  id: MAIN_CONTENT_ID,
  // -1: фокус принимает от ссылки, но в порядок Tab не входит;
  // outline-none — кольцо вокруг всей страницы не нужно, фокус виден
  // по прокрутке и по следующему элементу
  tabIndex: -1,
} as const;
