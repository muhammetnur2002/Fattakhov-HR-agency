/**
 * Ограничение частоты запросов (BR-29).
 *
 * Защищает публичные точки от перебора: пароля на форме входа и токенов
 * в ссылках для кандидатов. Токен угадать нельзя, но без лимита можно
 * пытаться бесконечно, а логи заполнятся мусором.
 *
 * Счётчики в памяти процесса. Для одного сервера этого достаточно;
 * при нескольких инстансах лимит станет мягче в N раз — не дыра,
 * но переезд на общее хранилище будет нужен. Отмечено в ТЗ 14.1.1.
 */

type Bucket = { count: number; resetAt: number };

const buckets = new Map<string, Bucket>();

/** Чтобы карта не росла бесконечно на длинных процессах. */
const MAX_BUCKETS = 10_000;

export type RateLimitResult = {
  allowed: boolean;
  /** Сколько секунд ждать до следующей попытки. */
  retryAfter: number;
};

export function checkRateLimit(
  key: string,
  limit: number,
  windowSeconds: number,
): RateLimitResult {
  const now = Date.now();
  const bucket = buckets.get(key);

  if (!bucket || bucket.resetAt <= now) {
    if (buckets.size >= MAX_BUCKETS) evictExpired(now);
    buckets.set(key, { count: 1, resetAt: now + windowSeconds * 1000 });
    return { allowed: true, retryAfter: 0 };
  }

  bucket.count++;

  if (bucket.count > limit) {
    return {
      allowed: false,
      retryAfter: Math.ceil((bucket.resetAt - now) / 1000),
    };
  }

  return { allowed: true, retryAfter: 0 };
}

function evictExpired(now: number): void {
  for (const [key, bucket] of buckets) {
    if (bucket.resetAt <= now) buckets.delete(key);
  }
}

/**
 * Адрес клиента.
 *
 * Заголовок X-Forwarded-For сам по себе НЕ защищён от подделки: его
 * присылает кто угодно, и первое значение в цепочке — то, что клиент
 * написал сам. Адрес можно считать настоящим только потому, что Caddy на
 * входе не дописывает в цепочку, а заменяет заголовок адресом соединения
 * (`header_up X-Forwarded-For {remote_host}`, infra/Caddyfile). Приложение
 * наружу без Caddy выставлять нельзя, а при смене прокси это правило
 * переносится вместе с ним: иначе лимиты и журнал входов считают по
 * адресу, который подставил атакующий, и обходятся одной строкой.
 */
export function clientIp(headers: Headers): string {
  const forwarded = headers.get("x-forwarded-for");
  if (forwarded) return forwarded.split(",")[0].trim();
  return headers.get("x-real-ip") ?? "unknown";
}

