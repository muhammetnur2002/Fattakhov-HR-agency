import { MAIN_CONTENT_ID } from "@/lib/a11y";

/**
 * «Перейти к содержимому» — первый элемент, до которого доходит Tab.
 *
 * Без неё клавиатурный пользователь пролистывал всю шапку и меню
 * (8–19 нажатий Tab в кабинете, замер 11.10.2026), прежде чем попадал
 * на саму страницу. Ссылка невидима, пока на ней нет фокуса, и появляется
 * плашкой под шапкой, а не поверх неё: у шапки там логотип и меню, закрывать
 * их нельзя. Вид — .skip-link в globals.css.
 *
 * Обычная якорная ссылка, а не кнопка со скриптом: работает и до загрузки
 * скриптов, а браузер по якорю сам переносит фокус на <main> (у него
 * tabIndex=-1, lib/a11y.ts).
 *
 * below — где кончается липкая шапка этой оболочки (CSS-выражение через
 * токен, например "var(--cabinet-header-h)"): плашка встаёт ниже её.
 */
export function SkipLink({ below }: { below?: string }) {
  return (
    <a
      href={`#${MAIN_CONTENT_ID}`}
      className="skip-link"
      style={below ? ({ "--skip-link-top": `calc(${below} + 0.5rem)` } as React.CSSProperties) : undefined}
    >
      Перейти к содержимому
    </a>
  );
}
