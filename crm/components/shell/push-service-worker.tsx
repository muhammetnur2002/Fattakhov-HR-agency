"use client";

import { useEffect } from "react";

import { registerPushWorker } from "@/lib/notifications/push-client";

/**
 * Регистрирует воркер пуш-уведомлений (public/push-sw.js).
 *
 * Только в кабинетах — макеты агентства и клиента выводят его, когда
 * пуш настроен на сервере; на сайте воркера нет и быть не должно.
 * Регистрация здесь, а не только по кнопке в настройках: установленный
 * на телефон кабинет открывается с дашборда, и к моменту, когда человек
 * дойдёт до настроек, воркер уже готов. Заодно браузер при каждом
 * заходе проверяет, не обновился ли файл воркера.
 *
 * Сам по себе воркер ничего не включает: подписка — только по кнопке
 * «Включить», с разрешения человека.
 */
export function PushServiceWorker() {
  useEffect(() => {
    void registerPushWorker();
  }, []);
  return null;
}
