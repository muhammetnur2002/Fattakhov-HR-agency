import type { CSSProperties, ReactNode } from "react";

import { CountUp } from "./count-up";
import { cn } from "@/lib/utils";

export { CountUp };

/**
 * Основа движения.
 *
 * Одно правило важнее остальных: всё здесь обязано выключаться при
 * системной настройке «уменьшить движение». Это не каприз и не режим
 * для слабых машин — у части людей от движущегося интерфейса реально
 * кружится голова. Поэтому каждый примитив спрашивает useReducedMotion
 * и в этом случае показывает конечное состояние сразу.
 *
 * Второе правило: движение обязано что-то сообщать. Появление объясняет,
 * откуда взялся блок; счётчик показывает, что число посчитано, а не
 * взято готовым. Постоянного покачивания «для живости» здесь нет
 * и не будет: в рабочем инструменте, где сидят по восемь часов,
 * оно превращается в раздражитель за первый же день.
 */

/**
 * Появление блока при прокрутке.
 *
 * Ни JS, ни наблюдателя: всё делает CSS через прокруточные таймлайны.
 * Причина не в экономии, а в отказоустойчивости. У любой схемы
 * «спрятать, потом показать по событию» отказ означает невидимый текст,
 * а для страницы, которую показывают клиентам, это не сломанная
 * анимация, а сломанная страница.
 *
 * С прокруточным таймлайном такого состояния нет: браузер либо
 * проигрывает анимацию, либо не умеет её вовсе и показывает обычный
 * блок. Правило спрятано за @supports, поэтому «не умеет» означает
 * ровно «без анимации», а не «без текста».
 *
 * Заодно это server component: в браузер не уезжает ни строчки кода.
 */
export function Reveal({
  children,
  className,
  delay = 0,
}: {
  children: ReactNode;
  className?: string;
  /** Сдвиг начала в долях прохода. Для соседних блоков в одном ряду. */
  delay?: number;
  distance?: number;
  once?: boolean;
}) {
  return (
    <div
      className={cn("reveal", className)}
      style={
        delay
          ? ({
              // Диапазон целиком, а не слагаемое: см. комментарий в globals.css
              "--reveal-range": `entry ${delay * 100}% entry ${40 + delay * 100}%`,
            } as CSSProperties)
          : undefined
      }
    >
      {children}
    </div>
  );
}

/**
 * Каскад: дети появляются по очереди.
 *
 * Задержка раздаётся детям в CSS по порядковому номеру. Шаг маленький
 * намеренно: большая задержка читается как медленный интерфейс,
 * а не как изящество.
 */
export function Stagger({
  children,
  className,
}: {
  children: ReactNode;
  className?: string;
  step?: number;
}) {
  return <div className={cn("stagger", className)}>{children}</div>;
}

/** Элемент каскада. Разметочная обёртка: очередь задаёт CSS. */
export function StaggerItem({
  children,
  className,
}: {
  children: ReactNode;
  className?: string;
}) {
  return <div className={className}>{children}</div>;
}

/**
 * Слой, едущий со своей скоростью при прокрутке.
 *
 * То самое «движение слоёв вверх и вниз»: соседние колонки смещаются
 * по-разному, и плоская страница читается как несколько планов.
 * Тоже на CSS и по той же причине: не умеет браузер - слой просто
 * стоит на месте, и ничего не ломается.
 *
 * Смещение небольшое намеренно. Сильный параллакс отрывает подписи
 * от того, что они подписывают, и на телефоне превращается в кашу.
 */
export function ParallaxLayer({
  children,
  className,
  shift = 60,
}: {
  children: ReactNode;
  className?: string;
  shift?: number;
}) {
  return (
    <div
      className={cn("parallax", className)}
      style={{ "--parallax-shift": `${shift}px` } as CSSProperties}
    >
      {children}
    </div>
  );
}
