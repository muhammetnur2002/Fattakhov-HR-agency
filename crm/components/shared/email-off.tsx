/**
 * Оборачивает email в маркер Cloudflare `email_off`.
 *
 * Не про наше приложение — про то, чем его иногда показывают: бесплатный
 * туннель trycloudflare.com (см. next.config.ts, allowedDevOrigins) идёт
 * через тот же контур Cloudflare, что и платные зоны, и его "Email Address
 * Obfuscation" на лету подменяет видимый адрес на свою ссылку-расшифровщик
 * плюс вставляет свой script. Итог виден только через туннель: гидратация
 * не совпадает с тем, что реально отрисовал сервер, — потому что между
 * сервером и браузером вклинился чужой рерайтер HTML. Официальный способ
 * Cloudflare попросить не трогать конкретный адрес — обернуть его
 * буквальным HTML-комментарием email_off. Обычный комментарий в JSX для
 * этого не годится — он не попадает в вывод вовсе, нужен настоящий узел
 * разметки, отсюда dangerouslySetInnerHTML ниже.
 *
 * Проверено вживую через сам туннель: маркер честно останавливает подмену
 * адреса на cdn-cgi-ссылку — ради этого всё и писалось. Но тот же туннель
 * по пути ещё и вырезает сами HTML-комментарии (похоже на общую
 * минификацию, не специфично для email) — маркеры до браузера не
 * долетают, и React видит несовпадение с тем, что сам же отрисовал на
 * сервере. suppressHydrationWarning здесь не маскирует баг, а называет
 * вещь тем, чем она является: невидимые комментарии, которые чужой
 * прокси может подрезать по дороге, ничего не значат для человека
 * на экране — ровно тот случай, для которого этот проп существует.
 *
 * Не только маркетинговые константы: то же самое нужно там, где страница
 * показывает чужой email (приглашение, сброс пароля) — он не хардкод,
 * поэтому перед вставкой в dangerouslySetInnerHTML экранируется отдельно,
 * а не только оборачивается.
 *
 * Текст вокруг email при этом не меняется ни на символ — важно для
 * LEAD_CONSENT_TEXT/MARKETING_CONSENT_TEXT (lib/legal/consent-texts.ts),
 * где сама формулировка зафиксирована версией из юридического пакета.
 */
function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

export function withEmailOff(text: string, email: string): React.ReactNode {
  const idx = text.indexOf(email);
  if (idx === -1) return text;

  return (
    <>
      {text.slice(0, idx)}
      {/* Маркеры-комментарии вокруг email — сам адрес экранирован, это
          не хардкод, см. пояснение над функцией */}
      <span
        suppressHydrationWarning
        dangerouslySetInnerHTML={{
          __html: `<!--email_off-->${escapeHtml(email)}<!--/email_off-->`,
        }}
      />
      {text.slice(idx + email.length)}
    </>
  );
}
