/**
 * Сетка публичного сайта: одна ось, один ритм, две пропорции колонок.
 *
 * Замеры 11.10.2026 на локальном сайте нашли в вёрстке семь «осей» там, где должна быть одна:
 * заголовки внутренних страниц стояли на 105/185/425px при логотипе шапки на 70, лента тарифов
 * обрывалась за 45px до края окна, а левый край второй колонки у двухколоночных блоков главной
 * лежал на семи разных расстояниях. Корень один — каждый блок писал свои числа руками. Здесь они
 * заданы один раз, а тесты (`tests/site-rhythm.test.ts`, `tests/e2e/site-grid.spec.ts`) не дают
 * вернуть копию.
 *
 * Классы лежат целыми словами: Tailwind собирает стили по исходникам как по тексту, и класс,
 * склеенный из частей, до CSS не дойдёт.
 */

/** Боковые поля сайта: 20 · 32 · 56 в rem-ступенях Tailwind (на ноутбуке — 25 · 40 · 70px). */
export const SITE_GUTTER = "px-5 md:px-8 xl:px-14";

/**
 * Выйти из боковых полей на их величину, чтобы лента прокрутки уходила под край окна.
 * Значения обязаны совпадать с `SITE_GUTTER` на каждой ширине: иначе лента обрывается
 * в пустоте, как было у тарифов (на 1280 и 1440 — за 45px до края).
 */
export const SITE_GUTTER_BLEED = "-mx-5 md:-mx-8 xl:-mx-14";

/**
 * Контейнер шапки, героев, разделов и подвала. Левый край заголовка, логотипа и карточки раздела
 * совпадает на любой ширине окна. Узкий раздел для чтения (`Section width="narrow"`) — единственное
 * сознательное исключение: он по центру и в колонку.
 */
export const SITE_CONTAINER = `mx-auto max-w-[2200px] ${SITE_GUTTER}`;

/**
 * Две пропорции колонок на весь сайт.
 *
 * - `SPLIT_EVEN` — две равные колонки (диагностика, кейс, «что входит» и «активный слот»);
 * - `SPLIT_MAIN` — основное и боковое, 1.15 к 0.85 (первый экран, кабинет, призыв к аудиту,
 *   блок студентов, зона ответственности).
 *
 * Промежуток тоже один на весь сайт: между колонками `gap-10` (с 1024), а когда колонки встали
 * друг под другом, `gap-6` — те же 24px, что были у блоков внутри карточек (кейсы, призыв к аудиту,
 * студенты, низ тарифов). Единый `gap-10` без ширины прибавил им 16px на телефоне (замечание
 * проверки к PR #118, 12.10.2026). Блок, которому нужна третья пропорция или другой промежуток, —
 * исключение с причиной в `tests/site-rhythm.test.ts`, а не новая цифра в разметке.
 */
export const SPLIT_EVEN = "grid gap-6 lg:gap-10 lg:grid-cols-2";
export const SPLIT_MAIN = "grid gap-6 lg:gap-10 lg:grid-cols-[1.15fr_0.85fr]";

/**
 * Та же пропорция 1.15/0.85 и тот же промежуток, но колонки — с 1280, а не с 1024.
 * Только для первого экрана главной: ценнику с ценой в 100px нужно 530px, и в 944px контейнера
 * на 1024 левая колонка оставалась 364px, абзац шёл в пять строк, а кнопки уезжали за сгиб
 * (844px при окне 768). Ниже 1280 абзац с кнопками идёт над ценником на всю ширину.
 */
export const SPLIT_MAIN_FROM_XL = "grid gap-6 xl:gap-10 xl:grid-cols-[1.15fr_0.85fr]";

/**
 * Интервал «заголовок раздела → содержимое». Его ставит сам `SectionHead`, поэтому содержимое
 * сразу под заголовком своего верхнего отступа не имеет (`mt-*` там запрещён тестом): иначе на
 * главной было 50px, на тарифах, аудите и кейсах — 30, а у списка диагностики — снова 30.
 */
export const SECTION_HEAD_GAP = "mb-10";
