import { headers } from "next/headers";
import type { MetadataRoute } from "next";

import { APP_ENTRY_PATHS, APP_ROOTS, isApplicationHost } from "@/lib/site-routing";
import { siteHost, siteOrigin } from "@/lib/urls";

/**
 * Закрытые пути сайта: все разделы приложения. Строится из `APP_ROOTS`, а не пишется
 * отдельно, чтобы новый раздел кабинета не оказался открытым для робота.
 *
 * Два пути с косой чертой в конце: «/a» без неё закрыл бы и «/audit», а «/api» —
 * только то, что внутри. Остальные — по первому сегменту, как есть.
 */
const PRIVATE_PATHS = APP_ROOTS.map((root) => (root === "a" || root === "api" ? `/${root}/` : `/${root}`));

/**
 * Правила для поисковых роботов.
 *
 * Файл отдаётся с обоих доменов и говорит с них разное.
 *
 * Сайт — витрина, её индексировать нужно, закрыты только кабинеты,
 * служебные маршруты и публичные ссылки по токенам. Последнее важнее
 * прочего: ссылка на форму согласия кандидата или на выбор времени
 * интервью содержит одноразовый токен, и попадание такой страницы
 * в индекс означало бы, что персональные данные конкретного человека
 * доступны из поиска.
 *
 * Домен приложения индексировать не нужно вовсе: там нет ни одной страницы для посторонних, а форма
 * входа в выдаче — ровно то, ради чего домены и разводили. Но запрет обхода (`Disallow: /`) и запрет
 * индекса (`noindex` в странице, `X-Robots-Tag` в ответе прокси) работают друг против друга: робот,
 * которому обход закрыт, страницу не загружает и запрета индекса не видит, а адрес с внешней ссылкой
 * остаётся в выдаче без описания (так сказано в справке Google; замечание проверки PR 13.10.2026). Поэтому
 * страницы, на которые ссылается сам сайт, — вход и регистрация (`APP_ENTRY_PATHS`), — роботу
 * читать можно: он увидит `noindex, nofollow` и выбросит адрес из выдачи. Всё остальное на адресе
 * приложения (кабинеты за входом, ссылки по токенам, `/api`) снаружи не линкуется и закрыто целиком:
 * по токен-ссылке страница с данными человека не должна даже загружаться роботом. Для них `noindex`
 * остаётся запасом на случай робота, который обход не запрещает, — гарантией выдачи он не является.
 *
 * Строки `Host:` нет: директива была только у Яндекса и устарела, он её больше
 * не учитывает, а Google не знал никогда. Основной адрес задают canonical и
 * перенаправление www.
 */
export default async function robots(): Promise<MetadataRoute.Robots> {
  const host = (await headers()).get("host");

  // Пока домены не разведены (siteHost() === null), всё живёт на одном
  // адресе, и закрывать его целиком нельзя — там же лендинг
  if (siteHost() !== null && isApplicationHost(host)) {
    return {
      // Самое длинное совпадение побеждает (Google, Яндекс): «/login» длиннее «/», вход открыт, остальное закрыто
      rules: { userAgent: "*", allow: [...APP_ENTRY_PATHS], disallow: "/" },
      // Карта сайта всё равно указывает на витрину: у приложения
      // своих страниц для поиска нет
      sitemap: `${siteOrigin()}/sitemap.xml`,
    };
  }

  return {
    rules: {
      userAgent: "*",
      allow: "/",
      disallow: PRIVATE_PATHS,
    },
    sitemap: `${siteOrigin()}/sitemap.xml`,
  };
}
