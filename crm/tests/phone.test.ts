/**
 * Номер телефона для входа: одна запись на один номер.
 *
 * «+7 (900) 123-45-67», «89001234567» и «9001234567» — один человек,
 * и храниться должны одинаково, иначе один номер заведёт три кабинета.
 */
import { describe, expect, it } from "vitest";

import { maskPhone, normalizeRuPhone, PhoneFormatError } from "@/lib/auth/phone";

describe("нормализация номера", () => {
  it.each([
    "+7 (900) 123-45-67",
    "8 900 123 45 67",
    "89001234567",
    "79001234567",
    "9001234567",
    "+7-900-123-45-67",
  ])("%s → +79001234567", (input) => {
    expect(normalizeRuPhone(input)).toBe("+79001234567");
  });

  it("городской номер тоже годится", () => {
    expect(normalizeRuPhone("+7 843 123-45-67")).toBe("+78431234567");
  });

  it("Казахстан (+7 7…) не принимаем: SMS туда не уйдёт", () => {
    expect(() => normalizeRuPhone("+7 701 123-45-67")).toThrow(PhoneFormatError);
  });

  it("короткий, длинный и пустой — ошибка с понятным текстом", () => {
    for (const input of ["12345", "+7 900 123-45-67-89", ""]) {
      expect(() => normalizeRuPhone(input)).toThrow(/российский/);
    }
  });
});

describe("маска номера", () => {
  it("прячет середину, оставляет узнаваемое", () => {
    expect(maskPhone("+79001234567")).toBe("+7 900 ***-**-67");
  });
});
