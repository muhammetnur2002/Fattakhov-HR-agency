/**
 * «В сети» / «был(а)…» — чистый форматтер (lib/presence.ts).
 *
 * Тот же формат, что у студенческой платформы: правила и тексты менять
 * в обоих местах сразу. Время — по Москве; «сейчас» задаётся параметром,
 * поэтому часы не подменяются вовсе.
 */
import { describe, expect, it } from "vitest";

import { formatPresence } from "@/lib/presence";

/** Момент по московскому времени: Москва — UTC+3 без перехода на летнее. */
function msk(iso: string): Date {
  return new Date(`${iso}+03:00`);
}

const NOW = msk("2026-10-04T22:00:00");

describe("formatPresence", () => {
  it.each([
    ["только что", "2026-10-04T22:00:00", true, "В сети"],
    ["минуту назад", "2026-10-04T21:59:00", true, "В сети"],
    ["ровно две минуты", "2026-10-04T21:58:00", true, "В сети"],
  ])("%s — в сети, с зелёной точкой", (_name, seen, online, text) => {
    expect(formatPresence(msk(seen), NOW)).toEqual({ online, text });
  });

  it("дрожание часов: отметка «из будущего» — тоже в сети", () => {
    expect(formatPresence(msk("2026-10-04T22:00:30"), NOW)).toEqual({ online: true, text: "В сети" });
  });

  it.each([
    ["чуть больше двух минут", "2026-10-04T21:57:30", "был(а) 2 мин назад"],
    ["5 минут", "2026-10-04T21:55:00", "был(а) 5 мин назад"],
    ["59 минут", "2026-10-04T21:01:00", "был(а) 59 мин назад"],
  ])("%s — «N мин назад», без точки", (_name, seen, text) => {
    expect(formatPresence(msk(seen), NOW)).toEqual({ online: false, text });
  });

  it.each([
    ["час назад — уже не минуты, а время", "2026-10-04T21:00:00", "был(а) сегодня в 21:00"],
    ["утром", "2026-10-04T09:05:00", "был(а) сегодня в 09:05"],
    ["сразу после полуночи", "2026-10-04T00:00:00", "был(а) сегодня в 00:00"],
  ])("%s", (_name, seen, text) => {
    expect(formatPresence(msk(seen), NOW)).toEqual({ online: false, text });
  });

  it("вчера — со временем", () => {
    expect(formatPresence(msk("2026-10-03T21:40:00"), NOW).text).toBe("был(а) вчера в 21:40");
    expect(formatPresence(msk("2026-10-03T00:00:00"), NOW).text).toBe("был(а) вчера в 00:00");
  });

  it("«сегодня» и «вчера» — по календарю Москвы, а не по прошедшим часам", () => {
    // 00:30 и 23:20 накануне — час десять разницы, но уже вчера
    const earlyMorning = msk("2026-10-04T00:30:00");
    expect(formatPresence(msk("2026-10-03T23:20:00"), earlyMorning).text).toBe("был(а) вчера в 23:20");
  });

  it("часовой пояс смотрящего не влияет: тот же момент — та же строка", () => {
    // 22:40 по UTC — это уже 01:40 следующих суток по Москве
    const seen = new Date("2026-10-03T22:40:00Z");
    expect(formatPresence(seen, msk("2026-10-04T22:00:00")).text).toBe("был(а) сегодня в 01:40");
  });

  it.each([
    ["12 сентября", "2026-09-12T10:00:00", "был(а) 12 сент."],
    ["2 октября (позавчера)", "2026-10-02T10:00:00", "был(а) 2 окт."],
    ["начало года", "2026-01-01T12:00:00", "был(а) 1 янв."],
    ["март", "2026-03-05T12:00:00", "был(а) 5 мар."],
    ["май — без точки", "2026-05-31T12:00:00", "был(а) 31 мая"],
  ])("в этом году — день и месяц: %s", (_name, seen, text) => {
    expect(formatPresence(msk(seen), NOW)).toEqual({ online: false, text });
  });

  it("вчера через границу месяца и года", () => {
    expect(formatPresence(msk("2026-09-30T21:40:00"), msk("2026-10-01T10:00:00")).text).toBe(
      "был(а) вчера в 21:40",
    );
    expect(formatPresence(msk("2025-12-31T21:40:00"), msk("2026-01-01T10:00:00")).text).toBe(
      "был(а) вчера в 21:40",
    );
  });

  it("прошлый год и старше — «давно»", () => {
    expect(formatPresence(msk("2025-12-31T10:00:00"), NOW)).toEqual({ online: false, text: "был(а) давно" });
    expect(formatPresence(msk("2020-01-01T10:00:00"), NOW).text).toBe("был(а) давно");
  });

  it("никогда не заходил или значение испорчено — «давно»", () => {
    expect(formatPresence(null, NOW)).toEqual({ online: false, text: "был(а) давно" });
    expect(formatPresence(undefined, NOW).text).toBe("был(а) давно");
    expect(formatPresence("не дата", NOW).text).toBe("был(а) давно");
  });

  it("принимает и строку ISO, и число — после передачи в браузер Date может прийти строкой", () => {
    expect(formatPresence("2026-10-04T18:55:00.000Z", NOW).text).toBe("был(а) 5 мин назад");
    expect(formatPresence(msk("2026-10-04T21:55:00").getTime(), NOW).text).toBe("был(а) 5 мин назад");
  });

  it("род не угадывается: везде «был(а)»", () => {
    for (const seen of ["2026-10-04T21:50:00", "2026-10-03T21:40:00", "2026-09-12T10:00:00", "2020-01-01T10:00:00"]) {
      expect(formatPresence(msk(seen), NOW).text).toMatch(/^был\(а\) /);
    }
  });
});
