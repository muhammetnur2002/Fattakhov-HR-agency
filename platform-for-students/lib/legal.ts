const LATER = 'будут указаны до запуска платформы';

function operatorLine(): string {
  if (LEGAL_REQUISITES_PENDING) {
    return `${OPERATOR.brand}. Полное наименование, ИНН, ОГРН и адрес оператора ${LATER}.`;
  }
  return `${OPERATOR.legalName} (${OPERATOR.brand}), ИНН ${OPERATOR.inn}, ОГРН ${OPERATOR.ogrn}, адрес: ${OPERATOR.address}.`;
}

function contactLine(): string {
  return OPERATOR.email ? `на почту ${OPERATOR.email}` : `на почту оператора (адрес ${LATER})`;
}

function hostingLine(): string {
  return HOSTING.name
    ? `${HOSTING.name}${HOSTING.address ? `, ${HOSTING.address}` : ''}`
    : `организации, которая обеспечивает хранение данных на серверах в России (наименование и адрес ${LATER})`;
}

