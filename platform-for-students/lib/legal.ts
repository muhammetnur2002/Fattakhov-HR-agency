/**
 * Юридические документы платформы: тексты, версии, реквизиты оператора.
 *
 * Согласие на обработку персональных данных — отдельный документ, а не
 * пункт соглашения: с 1 сентября 2025 года 152-ФЗ требует оформлять его
 * отдельно от других документов. Поэтому в регистрации три отметки, и у
 * каждой свой текст.
 *
 * Версия — дата редакции. Она записывается вместе с согласием: без неё не
 * доказать, на какой текст человек соглашался. Поменяли текст — меняйте
 * версию.
 *
 * Тексты — черновик до проверки юристом. Реквизиты оператора и хостинга
 * агентство пришлёт отдельно; пока их нет, документы говорят об этом прямо,
 * а не показывают выдуманные данные.
 */

export interface LegalSection {
  title: string;
  paragraphs?: string[];
  items?: string[];
}

export interface LegalDocument {
  slug: 'consent' | 'company-consent' | 'terms' | 'privacy';
  title: string;
  version: string;
  intro: string;
  sections: LegalSection[];
}

