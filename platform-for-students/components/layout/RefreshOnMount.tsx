'use client';

import { useEffect } from 'react';
import { useRouter } from 'next/navigation';

/**
 * Перечитывает каркас страницы один раз после открытия раздела.
 *
 * Раздел «Отклики» отмечает «просмотрено» при отрисовке страницы, а число на
 * значке в шапке каркас посчитал раньше — и при переходах между вкладками он
 * не перерисовывается, поэтому цифра висела, пока студент не обновит страницу
 * руками. Обновление после показа страницы пересчитывает значок уже по
 * свежей отметке.
 */
export function RefreshOnMount() {
  const router = useRouter();
  useEffect(() => {
    router.refresh();
  }, [router]);
  return null;
}
