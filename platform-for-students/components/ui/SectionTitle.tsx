import { cn } from '@/lib/utils';

/**
 * Заголовок раздела на публичных страницах (помощь, вузы, рейтинг).
 *
 * Раньше такие h2 были подписями капсом по 11px третьего уровня текста: мельче абзаца
 * под ними и бледнее его, так что страница читалась как сплошной текст без разделов
 * (а «Как считаем» в рейтинге вообще не отличался от строк списка). Размер — ступень `sub`
 * шкалы шрифтов (18px, README «Шкала шрифтов»): в 1,2 раза крупнее основного текста (15px) и заметно
 * темнее его. Заголовок внутри карточки был на 17px, вне карточки — на 20px; двух ступеней
 * между 15 и 24 в шкале нет, и оба стали `sub`: в карточке заголовок от этого на 1px крупнее
 * прежнего (17 → 18px), а отличается от абзаца и размером, и цветом, и весом. Цвет — основной текст, не faint.
 *
 * Роль h2 остаётся: меняется вид, а не разметка. Подпись капсом — для коротких меток
 * внутри форм (ProfileEditor), там она метка поля, а не заголовок раздела.
 */
export function SectionTitle({
  as: Tag = 'h2',
  className,
  children,
}: {
  as?: 'h2' | 'h3';
  className?: string;
  children: React.ReactNode;
}) {
  return <Tag className={cn('text-sub font-semibold leading-tight tracking-[-0.02em] text-paper', className)}>{children}</Tag>;
}
